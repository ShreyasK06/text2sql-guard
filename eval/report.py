"""Generate eval/results/RESULTS.md purely from the result CSV/JSON files. No hand-written numbers."""
from __future__ import annotations

import json
import math
from pathlib import Path

import pandas as pd

from app.types import LAYERS
from eval.plots import ATTACK_ROWS, COLUMN_GROUPS, SPLIT_ORDER, available_splits

REPO_ROOT = Path(__file__).resolve().parent.parent
ADVERSARIAL_DIR = REPO_ROOT / "eval" / "adversarial"


def _p(x, digits: int = 1) -> str:
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "n/a"
    return f"{100 * float(x):.{digits}f}%"


def _rate_ci(d: dict | None) -> str:
    if not d or d.get("rate") is None:
        return "n/a"
    return f"{_p(d['rate'])} [{_p(d.get('ci_lo'))}, {_p(d.get('ci_hi'))}]"


def _esc(s) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def md_table(headers: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        out.append("| " + " | ".join(_esc(c) for c in r) + " |")
    return "\n".join(out)


def _load_jsonl(split: str, items_root: Path | None = None) -> dict[str, dict]:
    path = (items_root or ADVERSARIAL_DIR) / "v1" / f"{split}.jsonl"
    items: dict[str, dict] = {}
    if path.exists():
        for line in path.read_text(encoding="utf-8").splitlines():
            if line.strip():
                it = json.loads(line)
                items[it["id"]] = it
    return items


def _fence(text: str, limit: int = 400) -> str:
    text = " ".join(str(text).split())
    if len(text) > limit:
        text = text[:limit] + " ..."
    return "`" + text.replace("`", "'") + "`"


def _per_category(summ: dict) -> str:
    rows = []
    for cat, d in summ["per_category"].items():
        rows.append([cat, d["n"], d["n_live"], _rate_ci(d["block_rate_all"]), _rate_ci(d["block_rate_live"])])
    return md_table(["category", "n", "n live", "block rate, all [95% CI]", "block rate, live [95% CI]"], rows)


def _ablation_table(df: pd.DataFrame) -> str:
    look = {(r["config"], r["category"]): r for _, r in df.iterrows()}
    cfgs = [c for _, cols in COLUMN_GROUPS for c, _ in cols]
    short = {c: lab.replace("\n", " ") for _, cols in COLUMN_GROUPS for c, lab in cols}
    rows = []
    for cat, label in ATTACK_ROWS:
        n = look.get(("full", cat))
        row = [f"{label} (n={int(n['n'])})" if n is not None else label]
        for c in cfgs:
            r = look.get((c, cat))
            row.append(_p(r["block_rate"], 0) if r is not None else "n/a")
        rows.append(row)
    nb = look.get(("full", "benign"))
    row = [f"benign: false-block rate (n={int(nb['n'])})" if nb is not None else "benign: false-block rate"]
    for c in cfgs:
        r = look.get((c, "benign"))
        row.append(_p(r["false_block_rate"], 0) if r is not None else "n/a")
    rows.append(row)
    return md_table(["% blocked (attacks) / % wrongly blocked (benign)"] + [short[c] for c in cfgs], rows)


def _attribution_table(df: pd.DataFrame) -> str:
    present = set(df["blocked_by"])
    layers = [l for l in (*LAYERS, "execution", "internal", "unknown", "none") if l in present]
    layers += [l for l in df["blocked_by"].unique() if l not in layers]
    rows = []
    for cat in df["category"].unique():
        sub = df[df["category"] == cat]
        row = [cat]
        for l in layers:
            m = sub[sub["blocked_by"] == l]
            row.append(int(m["n"].sum()) if len(m) else 0)
        row.append(int(sub["n"].sum()))
        rows.append(row)
    return md_table(["category"] + layers + ["total"], rows)


def _ms(x) -> str:
    return "n/a" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{float(x):.2f}"


def _latency_table(df: pd.DataFrame) -> str:
    rows = [[r["scope"], r["config"], int(r["n"]), _ms(r["median_ms"]), _ms(r["p95_ms"])] for _, r in df.iterrows()]
    overhead = ""
    e = df[df["scope"] == "end_to_end"].set_index("config")
    if {"full", "none"} <= set(e.index):
        d = e.loc["full", "median_ms"] - e.loc["none", "median_ms"]
        overhead = f"\n\nMedian end-to-end overhead of the full pipeline over no guards: {_ms(d)} ms (benign queries, cache bypassed)."
    return md_table(["scope", "config", "n", "median ms", "p95 ms"], rows) + overhead


def write_results_md(results_dir="eval/results", out="eval/results/RESULTS.md", items_root: Path | None = None) -> Path:
    rd = Path(results_dir)
    if not rd.is_absolute():
        rd = REPO_ROOT / rd
    outp = Path(out)
    if not outp.is_absolute():
        outp = REPO_ROOT / outp
    splits = available_splits(rd, SPLIT_ORDER)
    if not splits:
        raise FileNotFoundError(f"no ablation_<split>.csv in {rd}")

    lines: list[str] = [
        "# Evaluation results", "",
        "Generated by `eval/report.py` from the CSV/JSON files in this directory; no value is typed by hand. "
        "Attacks are fed as SQL (no LLM), so these numbers measure the guards against attacker-controlled SQL, "
        "not how often a real model would emit it. An attack is counted as blocked when it did not achieve its "
        "goal (oracle in `eval/oracle.py`). A \"live\" attack is one that succeeds with every guard off.", "",
    ]
    summaries = {s: json.loads((rd / f"summary_{s}.json").read_text(encoding="utf-8"))
                 for s in splits if (rd / f"summary_{s}.json").exists()}
    test_run = rd / "test_run.json"
    if test_run.exists():
        t = json.loads(test_run.read_text(encoding="utf-8"))
        lines += [f"Test suite at generation time: {t.get('passed', '?')} passed, {t.get('failed', '?')} failed, "
                  f"{t.get('skipped', '?')} skipped, {t.get('errors', '?')} errors.", ""]
    first = next(iter(summaries.values()), {})
    if first:
        lines += [f"Commit: `{first.get('git_commit') or 'unavailable'}`; policy limits: "
                  f"`{json.dumps(first.get('policy_limits', {}), sort_keys=True)}`.", ""]

    lines += ["## Headline", ""]
    if summaries:
        lines += [md_table(
            ["split", "attacks (n)", "live attacks (n)", "block rate, all [95% CI]", "block rate, live [95% CI]",
             "benign (n)", "false-block rate [95% CI]"],
            [[s["split"], s["n_attacks"], s["n_live"], _rate_ci(s["full_block_rate_all"]), _rate_ci(s["full_block_rate_live"]),
              s["n_benign"], _rate_ci(s["false_block_rate"])] for s in summaries.values()]), ""]
    for split in splits:
        lines += [f"## {split} split", ""]
        summ = summaries.get(split)
        if summ:
            lines += ["### Per category (full pipeline)", "", _per_category(summ), ""]
            c = summ.get("cache") or {}
            if c:
                lines += [f"Executor cache: {c.get('hits')} hits, {c.get('misses')} misses "
                          f"(hit rate {_p(c.get('hit_rate'))}); run at {summ.get('timestamp')}.", ""]
            for w in summ.get("oracle_warnings") or []:
                lines += [f"Oracle warning: {w}", ""]
        lines += ["### Ablation (figure data)", "", _ablation_table(pd.read_csv(rd / f"ablation_{split}.csv")), ""]
        attr = rd / f"attribution_{split}.csv"
        if attr.exists():
            lines += ["### Which layer stopped each attack (full pipeline; `none` = allowed, `execution` = database error)", "",
                      _attribution_table(pd.read_csv(attr)), ""]
        lat = rd / f"latency_{split}.csv"
        if lat.exists():
            lines += ["### Latency (benign queries)", "", _latency_table(pd.read_csv(lat)), ""]

        items = _load_jsonl(split, items_root)
        fi = rd / f"full_items_{split}.csv"
        if fi.exists():
            f = pd.read_csv(fi)
            f = f[f["config"] == "full"]
            att = f[(f["category"] != "benign") & (f["attack_succeeded"].astype(str) == "True")]
            lines += [f"### Residual attacks under the full pipeline ({len(att)})", ""]
            if len(att):
                rows = []
                for _, r in att.iterrows():
                    it = items.get(r["id"], {})
                    text = it.get("question") if r["entry"] == "question" else it.get("sql")
                    rows.append([r["id"], r["category"], r["subcategory"], r["role"], r["oracle_type"], _fence(text or "")])
                lines += [md_table(["id", "category", "subcategory", "role", "oracle", "question / SQL"], rows), ""]
            else:
                lines += ["None.", ""]
            fb = f[(f["category"] == "benign") & (f["false_block"].astype(str) == "True")]
            lines += [f"### False blocks of benign queries under the full pipeline ({len(fb)})", ""]
            if len(fb):
                def s(v):
                    return v if pd.notna(v) else ""
                rows = [[r["id"], r["role"], s(r["blocked_by"]), s(r["rule_id"]), s(r["reason"])] for _, r in fb.iterrows()]
                lines += [md_table(["id", "role", "layer", "rule", "reason"], rows), ""]
            else:
                lines += ["None.", ""]

    outp.parent.mkdir(parents=True, exist_ok=True)
    outp.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return outp


if __name__ == "__main__":
    print(write_results_md())
